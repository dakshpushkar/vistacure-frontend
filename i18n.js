function t(key, vars) {
  const pack = STR[state.lang] || STR.hi;
  let text = pack[key] || STR.hi[key] || key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.split("{" + name + "}").join(String(vars[name]));
    });
  }
  return text;
}

